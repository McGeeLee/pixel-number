import {readFile, readdir, mkdir, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const types = {'.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.svg': 'image/svg+xml', '.txt': 'text/plain; charset=utf-8'};
const assets = {};
for (const name of await readdir(path.join(root, 'public'))) {
  const body = await readFile(path.join(root, 'public', name), 'utf8');
  const etag = '"' + createHash('sha256').update(body).digest('hex').slice(0, 24) + '"';
  assets['/' + name] = {body, type: types[path.extname(name)], etag};
}
const source = `// Generated by scripts/build.mjs. Only public application assets are included.\nconst assets = ${JSON.stringify(assets)};\n` + `
export default {
  async fetch(request) {
    if (!['GET', 'HEAD'].includes(request.method)) return new Response('Method not allowed', {status: 405, headers: {Allow: 'GET, HEAD'}});
    const url = new URL(request.url);
    const key = url.pathname === '/' ? '/index.html' : url.pathname;
    const asset = assets[key];
    if (!asset) return new Response('Not found', {status: 404, headers: {'Content-Type': 'text/plain; charset=utf-8'}});
    const headers = {
      'Content-Type': asset.type,
      'Cache-Control': 'public, max-age=0, must-revalidate',
      'ETag': asset.etag,
      'X-Content-Type-Options': 'nosniff',
      'Referrer-Policy': 'no-referrer',
      'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
      'Content-Security-Policy': "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' blob: data:; worker-src 'self'; connect-src 'none'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'none'"
    };
    if (request.headers.get('If-None-Match') === asset.etag) return new Response(null, {status: 304, headers});
    return new Response(request.method === 'HEAD' ? null : asset.body, {headers});
  }
};\n`;
await mkdir(path.join(root, 'dist'), {recursive: true});
await writeFile(path.join(root, 'dist/worker.mjs'), source);
console.log(`Built ${Object.keys(assets).length} public assets, ${Buffer.byteLength(source).toLocaleString()} bytes.`);
